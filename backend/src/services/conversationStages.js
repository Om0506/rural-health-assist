export const STAGES = {
  IDLE: 'IDLE',
  ASKING_DURATION: 'ASKING_DURATION',
  ASKING_ADDITIONAL_SYMPTOMS: 'ASKING_ADDITIONAL_SYMPTOMS',
  ASKING_SEVERITY: 'ASKING_SEVERITY',
  PROVIDING_GUIDANCE: 'PROVIDING_GUIDANCE',
  ESCALATION_STAGE: 'ESCALATION_STAGE',
};

export const isAssessmentStage = (stage) =>
  [STAGES.ASKING_DURATION, STAGES.ASKING_ADDITIONAL_SYMPTOMS, STAGES.ASKING_SEVERITY].includes(
    stage
  );
